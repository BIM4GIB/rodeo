// Writes web/src/admin/geoData.ts from Natural Earth's 1:110m land and countries: a land mask a
// degree at a time (is the middle of each cell on land?) and a point inside each country, for
// the admin page's globe. Run it as
//   node web/scripts/admin-geo.ts <land.geojson> <countries.geojson> > web/src/admin/geoData.ts

import { readFileSync } from "node:fs";
import { Buffer } from "node:buffer";

const [landPath, countriesPath] = process.argv.slice(2);
if (!landPath || !countriesPath) {
  console.error("usage: node web/scripts/admin-geo.ts <land.geojson> <countries.geojson> > web/src/admin/geoData.ts");
  process.exit(1);
}

/** the mask's size: a cell a degree, rows from 90°N, columns from 180°W east */
const W = 360;
const H = 180;

/** [lon, lat] pairs: the outer ring first, then any holes */
type Rings = number[][][];

interface Feature {
  readonly properties?: Record<string, unknown> | null;
  readonly geometry: { readonly type: string; readonly coordinates: unknown } | null;
}

/** A polygon with its box, so most cells skip it at once. */
interface Area {
  readonly rings: Rings;
  readonly minX: number;
  readonly maxX: number;
  readonly minY: number;
  readonly maxY: number;
}

function polygonsOf(f: Feature): Rings[] {
  const g = f.geometry;
  if (!g) return [];
  if (g.type === "Polygon") return [g.coordinates as Rings];
  if (g.type === "MultiPolygon") return g.coordinates as Rings[];
  return [];
}

function areaOf(rings: Rings): Area {
  let minX = Infinity;
  let maxX = -Infinity;
  let minY = Infinity;
  let maxY = -Infinity;
  for (const [x, y] of rings[0]) {
    minX = Math.min(minX, x);
    maxX = Math.max(maxX, x);
    minY = Math.min(minY, y);
    maxY = Math.max(maxY, y);
  }
  return { rings, minX, maxX, minY, maxY };
}

/** Even-odd over every ring, so a point inside a hole is outside the polygon. */
function inside(area: Area, x: number, y: number): boolean {
  if (x < area.minX || x > area.maxX || y < area.minY || y > area.maxY) return false;
  let hit = false;
  for (const ring of area.rings) {
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [xi, yi] = ring[i];
      const [xj, yj] = ring[j];
      if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) hit = !hit;
    }
  }
  return hit;
}

const land = (JSON.parse(readFileSync(landPath, "utf8")) as { features: Feature[] }).features
  .flatMap(polygonsOf)
  .map(areaOf);

const bits = new Uint8Array(Math.ceil((W * H) / 8));
for (let row = 0; row < H; row++) {
  const lat = 90 - row - 0.5;
  for (let col = 0; col < W; col++) {
    const lon = col - 180 + 0.5;
    if (land.some((a) => inside(a, lon, lat))) {
      const i = row * W + col;
      bits[i >> 3] |= 0x80 >> (i & 7);
    }
  }
}

// the code is ISO_A2_EH where it is set, else ISO_A2 (ISO_A2 is -99 for France and Norway, for
// example); a feature with no usable code is left out
const countries = JSON.parse(readFileSync(countriesPath, "utf8")) as { features: Feature[] };
const centres = new Map<string, [number, number]>();
for (const f of countries.features) {
  const p = f.properties ?? {};
  const code = [p.ISO_A2_EH, p.ISO_A2].find((c): c is string => typeof c === "string" && /^[A-Z]{2}$/.test(c));
  const x = p.LABEL_X;
  const y = p.LABEL_Y;
  if (!code || typeof x !== "number" || typeof y !== "number" || centres.has(code)) continue;
  centres.set(code, [Number(y.toFixed(1)), Number(x.toFixed(1))]);
}

const rows = [...centres]
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
  .map(([code, [lat, lon]]) => `  ${code}: [${lat.toFixed(1)}, ${lon.toFixed(1)}],`);

const out = [
  "// Generated by web/scripts/admin-geo.ts from Natural Earth's 1:110m land and countries (public domain). Don't edit by hand.",
  "",
  "/** the land mask's size: one bit a degree, rows from 90°N down, columns from 180°W east */",
  `export const LAND_W = ${W};`,
  `export const LAND_H = ${H};`,
  "/** the mask, base64, LAND_W × LAND_H bits, row by row, most significant bit first */",
  `export const LAND_BITS = "${Buffer.from(bits).toString("base64")}";`,
  "/** a point inside each country (Natural Earth's label point), by its two-letter code: [lat, lon] */",
  "export const COUNTRY_CENTRES: Readonly<Record<string, readonly [number, number]>> = {",
  ...rows,
  "};",
  "",
].join("\n");

process.stdout.write(out);
