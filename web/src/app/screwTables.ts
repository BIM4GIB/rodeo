// Sizes for the Fastener tool's screws and bolts (screwShapes.ts), from the standards' tables:
// ASME B18.2.1 (hex, heavy hex and square bolts, hex cap and heavy hex screws) and B18.2.6
// (structural bolts), B18.3 (socket head, flat and button head socket cap screws), B18.6.2
// (slotted flat head cap screws) and B18.6.3 (slotted machine screws), inch; ASME B18.2.3.1M,
// 5M and 6M (hex cap screws, hex and heavy hex bolts), B18.3.1M (socket head cap screws),
// B18.6.7M (hex flange head machine screws) and IFI 513 (hex head machine screws), metric; ISO
// 4014, 4017, 7412, 4162, 4762, 10642 and 7380-1; DIN 931, 933, 7990, 6921, 912 and 7991. Heads
// are the tables' largest; thread lengths their b or LT columns, or the standards' rules where a
// column has none (2D + 1/4 in, 2d + 6 mm and so on).

import type { BoltThread } from "./boltShapes.ts";
import type { FastenerStandard } from "./fastenerShapes.ts";
import type { HeadKind, ScrewHead } from "./screwShapes.ts";

const INCH = 25.4;

/** size, nominal diameter, coarse and fine pitch (0 for none), thread lengths as the type's rule reads them, then the head as its kind reads it */
type ScrewRow = readonly [string, number, number, number, readonly number[], ...number[]];

/** How a type's thread length follows its length: by ASME B18.2.1's bands (6 in), ISO's (125 and 200 mm) or ISO 7412's (100 mm), one length for all, the whole length, or ASME B18.6.3's machine screw rule. */
type ThreadRule = "inch" | "metric" | "metric100" | "fixed" | "full" | "machine";

/** The thread length of a screw `length` long: its rows' lengths (mm) by its type's rule. */
function threadRule(rule: ThreadRule, b: readonly number[], diameter: number, length: number): number {
  switch (rule) {
    case "inch":
      return length <= 6 * INCH + 1e-6 ? b[0] : b[1];
    case "metric":
      return length <= 125 + 1e-6 ? b[0] : length <= 200 + 1e-6 ? b[1] : b[2];
    case "metric100":
      return length <= 100 + 1e-6 ? b[0] : b[1];
    case "fixed":
      return b.length ? b[0] : length;
    case "full":
      return length;
    case "machine": {
      // threaded to the head up to 2 in (No. 5 and under, 1-1/8 in), then at least 1.5 in (1 in)
      const small = diameter <= 0.13 * INCH;
      return length <= (small ? 1.125 : 2) * INCH + 1e-6 ? length : (small ? 1 : 1.5) * INCH;
    }
  }
}

const NO_HEAD: Omit<ScrewHead, "kind" | "width" | "height"> = { crown: 0, radius: 0, socket: null, slot: null, flange: null, washerFace: null, angle: 82, rounded: false };

/** the head a row's dimensions make for a head kind (in mm) */
function headOf(kind: HeadKind, d: readonly number[]): ScrewHead {
  const [width, height] = d;
  const base = { ...NO_HEAD, kind, width, height };
  switch (kind) {
    case "hex":
    case "square":
      return { ...base, washerFace: d[2] && d[3] ? { diameter: d[2], height: d[3] } : null };
    case "hexFlange":
      return { ...base, flange: { diameter: d[2], thickness: d[3] } };
    case "socket":
      return { ...base, socket: { flats: d[2], depth: d[3] } };
    case "flatSocket":
      return { ...base, socket: { flats: d[2], depth: d[3] }, angle: d[4] };
    case "buttonSocket":
      // a dome on a rim a sixth of the head's height (neither standard gives one)
      return { ...base, crown: height / 6, socket: { flats: d[2], depth: d[3] } };
    case "flat":
    case "round":
    case "truss":
      return { ...base, slot: { width: d[2], depth: d[3] } };
    case "oval":
    case "fillister":
      return { ...base, crown: d[2], slot: { width: d[3], depth: d[4] } };
    case "pan":
      return { ...base, radius: d[2], slot: { width: d[3], depth: d[4] } };
    default:
      return base;
  }
}

/** A screw size: its name (the nominal size, and for metric ones the pitch), nominal, diameter and pitches (mm), head, and thread length for a length. */
export interface ScrewSize {
  readonly id: string;
  readonly nominal: string;
  readonly diameter: number;
  readonly coarse: number | null;
  readonly fine: number | null;
  readonly head: ScrewHead;
  readonly threadLength: (length: number) => number;
}

/** A screw or bolt type of a standard, which of VW's groups it's in, and its sizes. */
export interface ScrewType {
  readonly id: string;
  readonly label: string;
  readonly standard: string;
  readonly group: "cap" | "hex" | "machine";
  readonly inch: boolean;
  readonly sizes: readonly ScrewSize[];
}

/** a screw type from its rows, in inches or mm */
function screws(id: string, label: string, standard: string, group: ScrewType["group"], kind: HeadKind, rule: ThreadRule, rows: readonly ScrewRow[], inch: boolean): ScrewType {
  const k = inch ? INCH : 1;
  const sizes = rows.map(([size, diameter, coarse, fine, b, ...d]): ScrewSize => {
    const lengths = b.map((x) => x * k);
    const D = diameter * k;
    const pitch = coarse || fine;
    return {
      id: inch ? size : `${size} × ${pitch}`,
      nominal: size,
      diameter: D,
      coarse: coarse ? coarse * k : null,
      fine: fine ? fine * k : null,
      // a flat socket head's fifth figure is its countersink's angle, in degrees
      head: headOf(kind, d.map((x, i) => (kind === "flatSocket" && i === 4 ? x : x * k))),
      threadLength: (length) => Math.min(length, threadRule(rule, lengths, D, length)),
    };
  });
  return { id, label, standard, group, inch, sizes };
}

/** The thread a size has in the series asked for (fine where it has no coarse, or the other way). */
export function screwThread(s: Pick<ScrewSize, "id" | "nominal" | "diameter" | "coarse" | "fine">, inch: boolean, fine: boolean): BoltThread {
  const pitch = (fine ? (s.fine ?? s.coarse) : (s.coarse ?? s.fine)) ?? 1;
  const series = pitch === s.coarse ? "UNC" : "UNF";
  return { id: inch ? `${s.nominal}-${Math.round((INCH / pitch) * 10) / 10} ${series}` : s.id, diameter: s.diameter, pitch, inch };
}

const NUMBERED = /^#/;

/** Metric preferred lengths (ISO 888's, as ISO 4014 lists them), mm. */
const METRIC_SCREW_LENGTHS: readonly number[] = [2, 2.5, 3, 4, 5, 6, 8, 10, 12, 14, 16, 18, 20, 22, 25, 28, 30, 35, 40, 45, 50, 55, 60, 65, 70, 75, 80, 90, 100, 110, 120, 130, 140, 150, 160, 180, 200, 220, 240, 260, 280, 300, 320, 340, 360, 380, 400, 420, 440, 460, 480, 500];

/** A standard length for `length`: the nearest (or, `up`, the next at least it) of ISO's lengths, or of inch screws' 1/16 in steps to 1/4 in, 1/8 to 1 in, 1/4 to 4 in, 1/2 to 6 in and whole inches past. */
export function standardScrewLength(length: number, inch: boolean, up = false): number {
  if (!inch) {
    const fit = up ? METRIC_SCREW_LENGTHS.find((l) => l >= length - 1e-6) : METRIC_SCREW_LENGTHS.reduce((best, l) => (Math.abs(l - length) < Math.abs(best - length) ? l : best));
    return fit ?? Math.ceil(length / 20) * 20;
  }
  const inches = length / INCH;
  const step = inches < 0.25 ? 1 / 16 : inches < 1 ? 1 / 8 : inches < 4 ? 1 / 4 : inches < 6 ? 1 / 2 : 1;
  const steps = inches / step;
  return Math.max(1 / 16, (up ? Math.ceil(steps - 1e-6) : Math.round(steps)) * step) * INCH;
}

/** Whether a size name is a numbered (machine screw) size, #0000 to #14. */
export const numbered = (s: ScrewSize): boolean => NUMBERED.test(s.nominal);

