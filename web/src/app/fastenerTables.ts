const washers = (id: string, label: string, standard: string, rows: readonly WasherRow[], inch: boolean): WasherType => {
  const k = inch ? INCH : 1;
  return { id, label, standard, sizes: rows.map(([size, inside, outside, thickness]) => ({ id: size, inside: inside * k, outside: outside * k, thickness: thickness * k })) };
};

