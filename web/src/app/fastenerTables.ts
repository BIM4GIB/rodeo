/** a nut type from its rows, in inches or mm; the thread's minor diameter is its basic one, major less 1.0825 pitches */
const nuts = (id: string, label: string, standard: string, shape: NutType["shape"], chamfered: Chamfered, rows: readonly NutRow[], inch: boolean): NutType => {
  const k = inch ? INCH : 1;
  const sizes = rows.map(([size, major, pitch, flats, height, faceDiameter = 0, faceHeight = 0, floor = 0, width = 0, crown = 0]) => ({
    id: size,
    major: major * k,
    minor: (major - 1.0825 * pitch) * k,
    flats: flats * k,
    height: height * k,
    face: faceDiameter ? { diameter: faceDiameter * k, height: faceHeight * k } : null,
    slots: floor ? { width: width * k, floor: floor * k, crown: crown ? crown * k : null } : null,
  }));
  return { id, label, standard, shape, chamfered, forms: sizes.some((s) => s.face), sizes };
};

